import fs from 'fs';
import path from 'path';
import sharp from 'sharp';

const ROOT_DIR = process.cwd();
const SRC_MAGZINE_DIR = path.join(ROOT_DIR, 'magzine');
const OUTPUT_MAG_DIR = path.join(ROOT_DIR, 'public', 'assets', 'magazine');

fs.mkdirSync(OUTPUT_MAG_DIR, { recursive: true });

const files = [
  { page: 1, file: '01Birthday Magazine_ Aanya Sharma Spotlight.png', title: 'Birthday Magazine • Aanya Sharma Spotlight' },
  { page: 2, file: '02The Aanya Issue_ Birthday Edition.png', title: 'The Aanya Issue • Birthday Edition' },
  { page: 3, file: '03More Life, Less Posing_ Birthday Favourites.png', title: 'More Life, Less Posing • Birthday Favourites' },
  { page: 4, file: '04A Birthday Broadcast_ The Aanya Issue.png', title: 'A Birthday Broadcast • The Soundtrack of 23' },
  { page: 5, file: '05A Little Warmth_ The Aanya Issue.png', title: 'A Little Warmth • The Aanya Issue' },
  { page: 6, file: '06Aesthetic Magazine Collage.png', title: 'Aesthetic Moments & Smiles' },
  { page: 7, file: '07Unfiltered_ The Aanya Issue.png', title: 'Unfiltered • Natural & True' },
  { page: 8, file: '08Together_ Good Company, Better Stories.png', title: 'Together • Good Company, Better Stories' },
  { page: 9, file: '09Details_ The Aanya Issue.png', title: 'The Details • Little Pauses' },
  { page: 10, file: '10Aanya Birthday Letter Collage.png', title: 'Aanya Birthday Letter Collage' },
  { page: 11, file: '11Becoming_ Chapter 23 Editorial Portrait.png', title: 'Becoming • Chapter 23 Editorial Portrait' },
  { page: 12, file: '12To Be Continued_ Aanya’s Birthday Editorial.png', title: 'To Be Continued • Aanya’s Birthday Back Cover' }
];

async function run() {
  console.log('--- Optimizing Custom Designed Magazine Pages ---');
  if (!fs.existsSync(SRC_MAGZINE_DIR)) {
    if (fs.existsSync(path.join(OUTPUT_MAG_DIR, 'page_01.webp'))) {
      console.log('Raw magzine/ folder already cleaned up and public/assets/magazine/ is fully populated. Skipping conversion.');
      return;
    }
    throw new Error(`Directory not found: ${SRC_MAGZINE_DIR}`);
  }

  const manifest = [];

  for (const item of files) {
    const srcPath = path.join(SRC_MAGZINE_DIR, item.file);
    if (!fs.existsSync(srcPath)) {
      throw new Error(`File not found: ${srcPath}`);
    }

    const numStr = String(item.page).padStart(2, '0');
    const webpOut = path.join(OUTPUT_MAG_DIR, `page_${numStr}.webp`);
    const jpgOut = path.join(OUTPUT_MAG_DIR, `page_${numStr}.jpg`);
    const thumbOut = path.join(OUTPUT_MAG_DIR, `page_${numStr}_thumb.webp`);

    console.log(`Processing Page ${item.page}: ${item.file}`);

    // High quality WebP (1055px width, crisp typography)
    await sharp(srcPath)
      .webp({ quality: 88, effort: 4 })
      .toFile(webpOut);

    // Fallback Progressive JPEG
    await sharp(srcPath)
      .jpeg({ quality: 88, progressive: true })
      .toFile(jpgOut);

    // Quick Thumbnail WebP
    await sharp(srcPath)
      .resize({ width: 360, withoutEnlargement: true })
      .webp({ quality: 75 })
      .toFile(thumbOut);

    const webpStat = fs.statSync(webpOut);
    manifest.push({
      page: item.page,
      title: item.title,
      webp: `assets/magazine/page_${numStr}.webp`,
      jpg: `assets/magazine/page_${numStr}.jpg`,
      thumb: `assets/magazine/page_${numStr}_thumb.webp`,
      sizeBytes: webpStat.size
    });
  }

  const code = `// AUTOGENERATED FILE - Custom Designed Magazine Pages
export interface DesignedMagazinePage {
  page: number;
  title: string;
  webp: string;
  jpg: string;
  thumb: string;
  sizeBytes: number;
}

export const DESIGNED_MAGAZINE_PAGES: DesignedMagazinePage[] = ${JSON.stringify(manifest, null, 2)};
`;

  fs.writeFileSync(path.join(ROOT_DIR, 'src', 'content', 'magazineDesignedPages.ts'), code, 'utf8');
  console.log('Successfully saved src/content/magazineDesignedPages.ts');
  console.log('--- Finished Magazine Pages Optimization ---');
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
